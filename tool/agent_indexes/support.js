const { targets } = require('./availability');

const hostGroups = [
  { label: '移动端', platforms: ['android', 'iOS'] },
  { label: '桌面端', platforms: ['macOS', 'windows'] },
  { label: 'Web', platforms: ['web'] },
];

function groupedPlatforms(platforms) {
  return hostGroups.map((group) => group.platforms.filter((host) => platforms.includes(host)).join('、') || '不支持');
}

// A projection of the same policy consumed by the catalog and guarded routes.
// Historical reports and test results are deliberately outside this input.
function supportDeclaration(modules) {
  return {
    schema: 'flutter_forge.module_support.v1',
    semantics: 'declared_entry_and_feature_support',
    target_platforms: targets,
    modules: modules.map((module) => {
      const policy = module.platformPolicy;
      const supported = targets.filter((host) => !module.excludedPlatforms.includes(host));
      const features = Object.fromEntries(Object.entries(policy.features)
        .map(([id, feature]) => [id, feature.platforms]));
      const limited = new Set([
        ...policy.required_capabilities.filter(() => supported.length < targets.length),
        ...Object.entries(policy.features).filter(([, feature]) => feature.platforms.length < supported.length).map(([id]) => id),
      ]);
      const limitations = policy.reasons.filter((reason) => limited.has(reason.capability));
      for (const [id, feature] of Object.entries(policy.features)) {
        if (limited.has(id) && !limitations.some((reason) => reason.capability === id)) {
          limitations.push({ capability: id, reason: feature.reason, sources: feature.sources });
        }
      }
      return {
        id: module.id, title: module.title, route: module.route,
        supported_platforms: supported,
        ...(Object.keys(features).length ? { features } : {}),
        ...(limitations.length ? { limitations } : {}),
        ...(policy.restriction ? { restriction: policy.restriction } : {}),
      };
    }),
  };
}

function writeSupport({ modules, facts, writeJson, writeText }) {
  const declaration = supportDeclaration(modules);
  writeJson('docs/module_availability/matrix.json', declaration);
  const cell = (value) => String(value).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
  const hostNote = facts
    ? `当前应用宿主目录：${facts.currentHosts.join('、')}。${facts.currentHosts.includes('ios') ? '' : 'iOS 当前仅建模，尚无应用宿主。'}`
    : '应用宿主接入范围见 [项目契约](../../AI_PROJECT_CONTEXT.md)。';
  const lines = ['# 模块支持声明', '', '<!-- GENERATED by tool/generate_agent_indexes.js - DO NOT EDIT -->', '',
    '日常维护仅声明入口支持范围、功能差异与必要限制；测试结果和历史验收状态不进入本表。', '',
    `目标平台为 Android、iOS、macOS、Web、Windows。${hostNote}入口声明不表示安装包或设备操作已完成验收。`, '',
    '移动端与桌面端按具体平台列出，端族内支持一端不代表支持另一端；Web 独立维护。窗口宽度只影响布局，不改变平台归属。', '',
    '| 模块 | 移动端 | 桌面端 | Web | 功能差异 | 限制依据 |', '|---|---|---|---|---|---|'];
  for (const module of declaration.modules) {
    const features = Object.entries(module.features ?? {}).map(([id, hosts]) => {
      const grouped = groupedPlatforms(hosts);
      return `${id}: ${hostGroups.map((group, index) => `${group.label}（${grouped[index]}）`).join('，')}`;
    }).join('；') || '—';
    const reasons = [...(module.limitations ?? []).map((item) => `${item.capability}: ${item.reason}`),
      ...(module.restriction ? [module.restriction.reason] : [])].join('；') || '—';
    lines.push(`| ${cell(module.title)}（\`${module.route}\`） | ${groupedPlatforms(module.supported_platforms).join(' | ')} | ${cell(features)} | ${cell(reasons)} |`);
  }
  lines.push('', '完整声明及限制来源见 [matrix.json](matrix.json)；维护方式见 [README](README.md)。', '');
  writeText('docs/module_availability/matrix.md', lines.join('\n'));
}

module.exports = { supportDeclaration, writeSupport };
