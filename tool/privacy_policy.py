#!/usr/bin/env python3
"""Render versioned policies from docs/privacy/policies.json; never publish them."""
import argparse
import hashlib
from html import escape
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def read_source(root=ROOT):
    return json.loads((root / 'docs/privacy/policies.json').read_text(encoding='utf-8'))


def policy_text(source, edition):
    policy = source['policies'][edition]
    paragraphs = [policy['title'], f"政策版本：{policy['id']}\n更新及生效日期：{policy['effective_date']}",
                  source['common']['identity'], policy['scope']]
    for part in policy['sections']:
        paragraphs.append(source['common'][part['common']] if 'common' in part else part['text'])
    paragraphs.append('平台差异\n' + '\n'.join(policy['platform_notes'].values()))
    return '\n\n'.join(paragraphs) + '\n'


def render_html(title, body):
    paragraphs = '\n'.join('<p>' + escape(p).replace('\n', '<br>') + '</p>' for p in body.strip().split('\n\n'))
    return f'''<!doctype html>
<html lang="zh-CN"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; base-uri 'none'; form-action 'none'">
<title>{escape(title)}</title>
<style>body{{margin:0;background:#f5f7fa;color:#172735;font:17px/1.8 system-ui,sans-serif}}main{{max-width:800px;margin:auto;padding:32px 20px}}article{{padding:24px;background:white;border-radius:16px}}h1{{font-size:26px}}p{{overflow-wrap:anywhere}}</style>
</head><body><main><h1>{escape(title)}</h1><article>
{paragraphs}
</article></main></body></html>
'''


def binding(edition, root=ROOT):
    source = read_source(root)
    policy = source['policies'][edition]
    text = policy_text(source, edition)
    return {'edition': edition, 'policy_id': policy['id'], 'text_sha256': sha256(text.encode()),
            'stable_path': policy['stable_path'], 'version_path': f"privacy/versions/{policy['id']}.html",
            'public_url': None, 'url_verification': 'needs_verification'}


def outputs(root=ROOT):
    source = read_source(root)
    result = {}
    histories = {}
    for path in sorted((root / 'docs/privacy/history').glob('*.json')):
        snapshot = json.loads(path.read_text(encoding='utf-8'))
        if snapshot['id'] != path.stem or snapshot['text_sha256'] != sha256(snapshot['text'].encode()):
            raise ValueError(f'Invalid policy snapshot: {path}')
        histories[snapshot['id']] = snapshot
    dart = ['// Generated by tool/privacy_policy.py. Edit docs/privacy/policies.json.', '']
    for edition, policy in source['policies'].items():
        if not re.fullmatch(r'(full|offline)-[0-9]{4}-[0-9]{2}-[0-9]{2}(\.[0-9]+)?', policy['id']):
            raise ValueError('Policy IDs must contain edition, date and optional revision')
        if not policy['id'].startswith(edition + '-'):
            raise ValueError('Policy edition does not match ID')
        text = policy_text(source, edition)
        snapshot = {'id': policy['id'], 'edition': edition, 'text': text, 'text_sha256': sha256(text.encode())}
        previous = histories.get(policy['id'])
        if previous and any(previous[key] != snapshot[key] for key in snapshot):
            raise ValueError(f"Policy {policy['id']} is immutable; create a new version")
        if not previous:
            result[f"docs/privacy/history/{policy['id']}.json"] = json.dumps(snapshot, ensure_ascii=False, indent=2) + '\n'
            histories[policy['id']] = snapshot
        result['apps/flutter_forge/web/' + policy['stable_path']] = render_html(policy['title'], text)
        for suffix, value in [('PrivacyVersion', policy['id']), ('SupportEmail', policy['support_email']), ('PrivacyPolicy', text)]:
            if "'''" in value:
                raise ValueError('Policy text cannot contain triple single quotes')
            dart.extend([f"const {edition}{suffix} = r'''{value}''';", ''])
    result['apps/flutter_forge/lib/app/privacy_policy_data.dart'] = '\n'.join(dart)
    index = {'schema': 'flutter_forge.privacy_index.v1', 'current': {}, 'versions': {}}
    for edition in source['policies']:
        index['current'][edition] = binding(edition, root)
    for key, snapshot in sorted(histories.items()):
        html = render_html(snapshot['text'].split('\n')[0], snapshot['text'])
        relative = f'apps/flutter_forge/web/privacy/versions/{key}.html'
        existing = root / relative
        if existing.exists() and existing.read_text(encoding='utf-8') != html:
            raise ValueError(f'Archived HTML is immutable: {relative}')
        result[relative] = html
        index['versions'][key] = {'edition': snapshot['edition'], 'text_sha256': snapshot['text_sha256'],
                                  'html_sha256': sha256(html.encode()), 'path': f'privacy/versions/{key}.html'}
    result['docs/privacy/index.json'] = json.dumps(index, ensure_ascii=False, indent=2) + '\n'
    return result


def generate(check=False, root=ROOT):
    rendered = outputs(root)
    drift = [relative for relative, text in rendered.items()
             if not (root / relative).is_file() or (root / relative).read_text(encoding='utf-8') != text]
    if check and drift:
        raise ValueError('Policy outputs differ: ' + ', '.join(drift))
    if not check:
        for relative, text in rendered.items():
            path = root / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8')
    return len(rendered)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        print(f'privacy: {generate(args.check)} outputs verified' if args.check else f'privacy: {generate()} outputs generated')
    except (ValueError, OSError, KeyError) as error:
        parser.exit(1, f'{error}\n')


if __name__ == '__main__':
    main()
